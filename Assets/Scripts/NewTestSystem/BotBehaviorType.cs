public enum BotBehaviorType
{
    Passive,     // Только собирает монетки и захватывает территории
    Aggressive,  // Активно атакует игроков и их trail
    Balanced,    // Сбалансированное поведение
    Collector,   // Фокусируется на сборе монеток и бустеров
    Defender,    // Защищает свою территорию
    Hunter       // Охотится на других игроков
}